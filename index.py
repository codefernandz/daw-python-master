# Operadores y Conversión de Datos en Python

# Operadores Aritméticos
# Suma (+): Suma dos valores numéricos.
# Resta (-): Resta un valor del otro.
# Multiplicación (*): Multiplica dos valores.
# División (/): Divide dos valores y devuelve un número flotante (incluso si ambos son enteros).
# División entera (//): Devuelve solo la parte entera de la división.
# Módulo (%): Devuelve el residuo de la división.
# Potencias ()**: Eleva un número a la potencia de otro.

# Operador Suma para Concatenar Strings
saludo = "Hola, "
nombre = "Ana"
mensaje = saludo + nombre
print(mensaje)  # Salida: Hola, Ana